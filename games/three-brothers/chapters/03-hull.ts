/** Rob's stock of grumbles when the same thing is tried on any stone parcel. */
function parcel(id: string, owner: string, wrong: string): Rule[] {
  return [
    { on: id, item: 'strap', if: '!ledger_open', say: ['Warden: Oi! Hands off. Nobody touches a parcel without it being in my book, and nobody sees my book.'] },
    { on: id, item: 'strap', say: [`Warden: That's ${owner}'s, that is. It says so in the book. Leave it be.`, wrong] },
    { on: id, if: 'ledger_open', say: ["Me: It's crusted solid onto the hook. Bare hands won't shift it, and that's saying something."] },
    { on: id, say: ["Me: It's crusted solid onto the hook. I could lift it easily, obviously, if it would come off. And whose even is it?"] },
  ];
}

