/** The same line for an item used on anything that has no rule of its own. */
function anywhere(item: string, line: string): Rule {
  return { on: '*', item, say: [line] };
}

/** Going somewhere. */
function exit(on: string, to: string, line: string): Rule {
  return { on, say: [line], do: [`goto:${to}`] };
}

